#!/usr/bin/env bash
# One-command factory bring-up through serve.
# Automates: Node check → npm install → validate → auth check → product-repo
# env file → optional login → optional serve.
#
# MCP connectors (Atlassian / GitHub) still need a one-time Cursor dashboard
# click — the script prints that checklist; it cannot OAuth for you.
#
# Usage (from a software-factory checkout):
#   ./scripts/setup-factory.sh --product-repo owner/name
#   ./scripts/setup-factory.sh --product-repo owner/name --product-path ../my-app --serve
#   ./scripts/setup-factory.sh --product-repo owner/name --login --serve
#
# Env overrides (same names written to .env.factory):
#   FACTORY_PRODUCT_REPO, FACTORY_PRODUCT_REPO_PATH, FACTORY_PRODUCT_DEFAULT_BRANCH,
#   FACTORY_JIRA_PROJECT / JIRA_PROJECT_KEY

set -euo pipefail

BDK_PKG="@grok/agent-sdk@0.4.0"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT}/.env.factory"
MIN_NODE_MAJOR=22
MIN_NODE_MINOR=13

PRODUCT_REPO="${FACTORY_PRODUCT_REPO:-${PRODUCT_REPO:-}}"
PRODUCT_PATH="${FACTORY_PRODUCT_REPO_PATH:-${PRODUCT_REPO_PATH:-}}"
DEFAULT_BRANCH="${FACTORY_PRODUCT_DEFAULT_BRANCH:-${PRODUCT_DEFAULT_BRANCH:-main}}"
JIRA_PROJECT="${FACTORY_JIRA_PROJECT:-${JIRA_PROJECT_KEY:-}}"
DO_LOGIN=0
DO_SERVE=0
SKIP_INSTALL=0
SKIP_VALIDATE=0
ALLOW_ANON=0
NONINTERACTIVE=0

usage() {
  cat <<'EOF'
setup-factory.sh — bring the software factory up through serve

Required (unless already in env / .env.factory):
  --product-repo owner/name   GitHub product repo the implementer targets

Optional:
  --product-path PATH         Local checkout of the product repo
  --default-branch BRANCH     PR base branch (default: main)
  --jira-project KEY          Default Jira project key
  --login                     Run agent-sdk login when not signed in
  --serve                     Start peer network after setup
  --allow-anonymous           Pass anonymous serve flags (trusted networks only)
  --skip-install              Skip npm install
  --skip-validate             Skip agent-sdk validate
  --non-interactive           Fail instead of prompting for missing values
  -h, --help                  Show this help

Examples:
  ./scripts/setup-factory.sh --product-repo acme/widget --serve
  ./scripts/setup-factory.sh --product-repo acme/widget --product-path ../widget --login --serve

After setup, open http://127.0.0.1:3000/orchestrator/playground and follow docs/smoke-e2e.md
EOF
}

log() { printf '==> %s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

run_bdk() {
  npx --yes "${BDK_PKG}" "$@"
}

have_cursor_cred() {
  if [[ -n "${CURSOR_API_KEY:-}" || -n "${CURSOR_SERVICE_ACCOUNT_KEY:-}" ]]; then
    return 0
  fi
  if [[ -n "${CURSOR_API_KEY_FILE:-}" && -f "${CURSOR_API_KEY_FILE}" ]]; then
    return 0
  fi
  # whoami succeeds only when a stored login or env key is present
  if run_bdk whoami --json >/dev/null 2>&1; then
    return 0
  fi
  return 1
}

prompt_if_needed() {
  local var_name="$1"
  local prompt="$2"
  local current="${!var_name:-}"
  if [[ -n "${current}" ]]; then
    return 0
  fi
  if [[ "${NONINTERACTIVE}" -eq 1 || ! -t 0 ]]; then
    die "missing ${var_name}. Pass a flag or set the env var (non-interactive)."
  fi
  read -r -p "${prompt}: " current
  printf -v "${var_name}" '%s' "${current}"
}

load_existing_env() {
  if [[ ! -f "${ENV_FILE}" ]]; then
    return 0
  fi
  # shellcheck disable=SC1090
  set -a
  # shellcheck disable=SC1091
  source "${ENV_FILE}"
  set +a
  PRODUCT_REPO="${PRODUCT_REPO:-${FACTORY_PRODUCT_REPO:-${PRODUCT_REPO:-}}}"
  PRODUCT_PATH="${PRODUCT_PATH:-${FACTORY_PRODUCT_REPO_PATH:-${PRODUCT_REPO_PATH:-}}}"
  DEFAULT_BRANCH="${DEFAULT_BRANCH:-${FACTORY_PRODUCT_DEFAULT_BRANCH:-${PRODUCT_DEFAULT_BRANCH:-main}}}"
  JIRA_PROJECT="${JIRA_PROJECT:-${FACTORY_JIRA_PROJECT:-${JIRA_PROJECT_KEY:-}}}"
}

write_env_file() {
  local path_line="" project_line=""
  if [[ -n "${PRODUCT_PATH}" ]]; then
    path_line="FACTORY_PRODUCT_REPO_PATH=${PRODUCT_PATH}"
  fi
  if [[ -n "${JIRA_PROJECT}" ]]; then
    project_line="FACTORY_JIRA_PROJECT=${JIRA_PROJECT}"
  fi
  cat >"${ENV_FILE}" <<EOF
# Generated by scripts/setup-factory.sh — local only (gitignored)
FACTORY_PRODUCT_REPO=${PRODUCT_REPO}
FACTORY_PRODUCT_DEFAULT_BRANCH=${DEFAULT_BRANCH}
${path_line}
${project_line}
EOF
  # Drop blank lines left by optional empties
  sed -i '/^$/d' "${ENV_FILE}"
  log "Wrote ${ENV_FILE}"
}

check_node() {
  command -v node >/dev/null 2>&1 || die "Node.js not found. Install Node ${MIN_NODE_MAJOR}.${MIN_NODE_MINOR}+ (never Bun)."
  local ver major minor
  ver="$(node -v | sed 's/^v//')"
  major="${ver%%.*}"
  minor="${ver#*.}"
  minor="${minor%%.*}"
  if (( major < MIN_NODE_MAJOR )) || { (( major == MIN_NODE_MAJOR )) && (( minor < MIN_NODE_MINOR )); }; then
    die "Node ${MIN_NODE_MAJOR}.${MIN_NODE_MINOR}+ required (found v${ver}). Never use Bun."
  fi
  log "Node v${ver} OK"
}

parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --product-repo)
        PRODUCT_REPO="${2:-}"
        shift 2
        ;;
      --product-path)
        PRODUCT_PATH="${2:-}"
        shift 2
        ;;
      --default-branch)
        DEFAULT_BRANCH="${2:-}"
        shift 2
        ;;
      --jira-project)
        JIRA_PROJECT="${2:-}"
        shift 2
        ;;
      --login) DO_LOGIN=1; shift ;;
      --serve) DO_SERVE=1; shift ;;
      --allow-anonymous) ALLOW_ANON=1; shift ;;
      --skip-install) SKIP_INSTALL=1; shift ;;
      --skip-validate) SKIP_VALIDATE=1; shift ;;
      --non-interactive) NONINTERACTIVE=1; shift ;;
      -h|--help) usage; exit 0 ;;
      *) die "unknown argument: $1 (try --help)" ;;
    esac
  done
}

print_mcp_checklist() {
  cat <<'EOF'

MCP connectors (one-time, Cursor dashboard — not automatable here):
  [ ] Atlassian  — product, design, architect, implementer, reviewer
  [ ] GitHub     — implementer, reviewer

Dashboard: Cursor Settings → MCP / connectors
Hosted deploys: attach the same servers under each deploy slug.

EOF
}

print_next_steps() {
  cat <<EOF

Setup complete through serve prerequisites.

Next (manual — docs/smoke-e2e.md):
  1. Create/pick a Jira ticket; label it exactly: prd_draft
  2. Open http://127.0.0.1:3000/orchestrator/playground
  3. Say: Ticket <KEY> is in prd_draft. Route it through the factory.
  4. Approve each *_review gate yourself.

Re-serve later:
  ./scripts/serve-factory.sh
  # or: npm run serve:factory

EOF
}

main() {
  cd "${ROOT}"
  parse_args "$@"
  load_existing_env

  log "Factory root: ${ROOT}"
  check_node

  prompt_if_needed PRODUCT_REPO "Product GitHub repo (owner/name)"
  [[ "${PRODUCT_REPO}" == */* ]] || die "--product-repo must look like owner/name (got: ${PRODUCT_REPO})"

  if [[ -n "${PRODUCT_PATH}" ]]; then
    [[ -d "${PRODUCT_PATH}" ]] || die "--product-path is not a directory: ${PRODUCT_PATH}"
    # Resolve to absolute for the env file
    PRODUCT_PATH="$(cd "${PRODUCT_PATH}" && pwd)"
  fi

  if [[ "${SKIP_INSTALL}" -eq 0 ]]; then
    log "npm install"
    npm install
  else
    log "Skipping npm install"
  fi

  if [[ "${SKIP_VALIDATE}" -eq 0 ]]; then
    log "Validating agents"
    run_bdk validate --dir ./agents
    if [[ -d ./examples/app-host ]]; then
      run_bdk validate --dir ./examples/app-host || warn "app-host validate reported issues (often OK if orchestrator peer is unresolved)"
    fi
  else
    log "Skipping validate"
  fi

  write_env_file
  # Export for this process / optional serve child
  set -a
  # shellcheck disable=SC1090
  source "${ENV_FILE}"
  set +a

  if have_cursor_cred; then
    log "Cursor credential present (whoami / env key)"
  else
    warn "Not signed in to Cursor (model turns and account MCP need auth)."
    if [[ "${DO_LOGIN}" -eq 1 ]]; then
      log "Running agent-sdk login"
      run_bdk login
      have_cursor_cred || die "Still not signed in after login"
    elif [[ "${ALLOW_ANON}" -eq 1 ]]; then
      warn "Continuing with --allow-anonymous (trusted networks only)."
    else
      warn "Re-run with --login, set CURSOR_API_KEY, or pass --allow-anonymous for local playground only."
    fi
  fi

  print_mcp_checklist

  if [[ "${DO_SERVE}" -eq 1 ]]; then
    log "Starting peer network (Ctrl+C to stop)"
    print_next_steps
    if [[ "${ALLOW_ANON}" -eq 1 ]]; then
      exec npx --yes "${BDK_PKG}" serve --dir ./agents --dev \
        --allow-anonymous --allow-anonymous-cursor-account-mcp
    fi
    exec npx --yes "${BDK_PKG}" serve --dir ./agents --dev
  fi

  print_next_steps
  log "Start peers with: ./scripts/serve-factory.sh"
}

main "$@"
